#!/usr/bin/env node
/**
 * Builds schema/storefront.graphql — a single storefront schema that mirrors what an
 * Adobe API Mesh combining Commerce Core GraphQL and Catalog Service exposes.
 *
 * Merge rules (Catalog Service wins where the two disagree, because the drop-ins send
 * catalog queries such as `products(skus:)` and `categories` to the catalog endpoint):
 * - Query.products / Query.categories use the Catalog Service signatures.
 * - Catalog-only Query fields (productSearch, refineProduct, variants, attributeMetadata,
 *   recommendations, recommendationsByUnitIds) are added.
 * - Shared object/interface types gain catalog-only fields; conflicting field types take
 *   the Catalog Service definition. Shared enums are unioned.
 *
 * Also emits lib/schema-sdl.js so actions can bundle the SDL without filesystem access.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildSchema, printSchema, parse, print, Kind,
} from 'graphql';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const coreDoc = parse(read('schema/reference/core.graphql'));
const csDoc = parse(read('schema/reference/catalog-service.graphql'));

const OBJECTLIKE = new Set([
  Kind.OBJECT_TYPE_DEFINITION, Kind.INTERFACE_TYPE_DEFINITION, Kind.INPUT_OBJECT_TYPE_DEFINITION,
]);

const defs = new Map();
coreDoc.definitions.forEach((d) => defs.set(d.name?.value ?? Symbol('anon'), d));

const argNames = (field) => (field.arguments || []).map((a) => a.name.value).sort().join(',');

const stats = { added: 0, mergedFields: 0, replacedFields: 0, enumValues: 0 };

csDoc.definitions.forEach((cs) => {
  const name = cs.name?.value;
  if (!name) return;
  const core = defs.get(name);
  if (!core) {
    defs.set(name, cs);
    stats.added += 1;
    return;
  }
  if (OBJECTLIKE.has(cs.kind) && cs.kind === core.kind) {
    const fields = new Map(core.fields.map((f) => [f.name.value, f]));
    cs.fields.forEach((f) => {
      const existing = fields.get(f.name.value);
      if (!existing) {
        fields.set(f.name.value, f);
        stats.mergedFields += 1;
      } else if (print(existing.type) !== print(f.type) || argNames(existing) !== argNames(f)) {
        fields.set(f.name.value, f);
        stats.replacedFields += 1;
      }
    });
    const interfaces = new Map([...(core.interfaces || []), ...(cs.interfaces || [])]
      .map((i) => [i.name.value, i]));
    defs.set(name, { ...core, fields: [...fields.values()], interfaces: [...interfaces.values()] });
    return;
  }
  if (cs.kind === Kind.ENUM_TYPE_DEFINITION && core.kind === cs.kind) {
    const values = new Map(core.values.map((v) => [v.name.value, v]));
    cs.values.forEach((v) => {
      if (!values.has(v.name.value)) {
        values.set(v.name.value, v);
        stats.enumValues += 1;
      }
    });
    defs.set(name, { ...core, values: [...values.values()] });
    return;
  }
  if (cs.kind === Kind.UNION_TYPE_DEFINITION && core.kind === cs.kind) {
    const types = new Map([...core.types, ...cs.types].map((t) => [t.name.value, t]));
    defs.set(name, { ...core, types: [...types.values()] });
  }
});

// Project-owned storefront extensions (e.g. promotions/recovery offers).
const EXTENSIONS = ['schema/promotions.graphql', 'schema/of1.graphql'];
const merged = {
  kind: Kind.DOCUMENT,
  definitions: [...defs.values(), ...EXTENSIONS.flatMap((p) => parse(read(p)).definitions)],
};
const schema = buildSchema(print(merged));
const sdl = printSchema(schema);

fs.writeFileSync(path.join(root, 'schema/storefront.graphql'), sdl);
fs.writeFileSync(
  path.join(root, 'lib/schema-sdl.js'),
  `// Generated by scripts/build-schema.mjs — do not edit.\nmodule.exports = ${JSON.stringify(sdl)};\n`,
);
console.log(`storefront.graphql written (${sdl.length} chars)`, stats);
